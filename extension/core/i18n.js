export function normalizeLanguage(value) {
  return LANGUAGES.includes(value) ? value : "en";
}

export function translate(language, key, params = {}) {
  const template = messages[normalizeLanguage(language)][key] ?? messages.en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (token, name) => String(params[name] ?? token));
}

// Retain message keys so changing language can update live status and results
// without replacing controls, input values, focus, or page excerpts.
export function setMessage(element, key, params = {}, language = "en") {
  element.dataset.i18n = key;
  element.dataset.i18nParams = JSON.stringify(params);
  element.textContent = translate(language, key, params);
}

export function localize(root, language) {
  for (const element of root.querySelectorAll("[data-i18n]")) {
    element.textContent = translate(language, element.dataset.i18n, JSON.parse(element.dataset.i18nParams || "{}"));
  }
  for (const attribute of ["placeholder", "title", "aria-label"]) {
    for (const element of root.querySelectorAll(`[data-i18n-${attribute}]`)) {
      element.setAttribute(attribute, translate(language, element.getAttribute(`data-i18n-${attribute}`)));
    }
  }
}
